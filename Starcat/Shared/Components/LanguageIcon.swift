/// 根据语言名解析 Devicon 资源名（仅当 asset 实际存在时返回）
/// 优先顺序：1. 特殊映射 2. 大小写不敏感直接匹配（去空格后 lowercase）
private func deviconAssetName(for language: String) -> String? {
    // 1. 特殊映射
    if let special = deviconSpecialMap[language], validDeviconAssets.contains(special) {
        return special
    }

    // 2. 大小写不敏感直接匹配（去空格后 lowercase）
    let normalized = language.lowercased().replacingOccurrences(of: " ", with: "")
    if validDeviconAssets.contains(normalized) {
        return normalized
    }

    return nil
}

