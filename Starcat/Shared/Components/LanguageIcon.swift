// MARK: - 数据模型

/// 语言元数据，来源：GitHub Linguist languages.yml
struct LanguageMeta: Codable, Equatable {
    let type: String           // "programming" | "markup" | "data" | "prose"
    let color: String?        // Hex color, e.g. "#f1e05a"
    let aliases: [String]

    init(type: String, color: String?, aliases: [String] = []) {
        self.type = type
        self.color = color
        self.aliases = aliases
    }
}

/// 语言图标解析结果
struct LanguageIconResult {
    enum IconType {
        case localSVG(assetName: String)  // 本地 asset catalog 中的 SVG 资源名
        case badge(colorHex: String, label: String)  // 彩色圆形 + 首字母
    }

    let type: IconType
    let languageName: String

    /// 获取本地资源名（如果是本地 SVG 的话）
    var localAssetName: String? {
        if case .localSVG(let name) = type {
            return name
        }
        return nil
    }

    /// 是否使用 badge
    var isBadge: Bool {
        if case .badge = type { return true }
        return false
    }

    /// Badge 背景色 hex
    var badgeColorHex: String? {
        if case .badge(let colorHex, _) = type {
            return colorHex
        }
        return nil
    }

    /// Badge 标签（首字母）
    var badgeLabel: String? {
        if case .badge(_, let label) = type {
            return label
        }
        return nil
    }
}

