// MARK: - 语言图标解析器

/// 语言图标解析器
/// 解析 GitHub 语言名 → 本地 Devicon SVG 或 Badge fallback
enum LanguageIconResolver {

    /// 解析语言名对应的图标结果
    /// 优先级: 本地 Devicon SVG → ColorBadge fallback
    static func resolve(language: String) -> LanguageIconResult {
        // Step 1: 尝试本地 Devicon SVG
        if let assetName = deviconAssetName(for: language) {
            return LanguageIconResult(
                type: .localSVG(assetName: assetName),
                languageName: language
            )
        }

        // Step 2: Fallback - 使用 Linguist color 或默认灰色 + 首字母
        let meta = linguistLanguages[language]
        let color = meta?.color ?? "#808080"  // 默认灰色
        let label = String(language.prefix(1)).uppercased()

        return LanguageIconResult(
            type: .badge(colorHex: color, label: label),
            languageName: language
        )
    }

    /// 获取语言对应的颜色（用于 RepoRowView 的 LanguageColor 兼容）
    static func color(for language: String) -> Color {
        linguistLanguages[language]?.color
            .flatMap { Color(hex: $0) }
            ?? .gray
    }

    /// 检查是否有本地 SVG 图标
    static func hasLocalSVG(language: String) -> Bool {
        deviconAssetName(for: language) != nil
    }
}

// MARK: - SwiftUI 视图

/// 语言图标视图：显示语言 logo 或 fallback badge
/// 使用场景：SidebarView 的 Languages 列表行
struct LanguageIconView: View {
    let language: String
    let size: CGFloat

    init(language: String, size: CGFloat = 20) {
        self.language = language
        self.size = size
    }

    var body: some View {
        let result = LanguageIconResolver.resolve(language: language)

        switch result.type {
        case .localSVG(let assetName):
            Image(assetName)
                .resizable()
                .scaledToFill()
                .frame(width: size, height: size)
                .clipped()

        case .badge(let colorHex, _):
            // Fallback: 只显示彩色圆形，不显示字母
            let color = Color(hex: colorHex) ?? .gray
            Circle()
                .fill(color)
                .frame(width: size, height: size)
        }
    }
}
