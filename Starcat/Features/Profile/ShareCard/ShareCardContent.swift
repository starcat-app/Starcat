//  HOM-173 用户分享卡片：纯视觉卡片本体（"星际杂志卡 v2"布局）。
//
//  本 View 是**唯一的卡片视觉真源**，被两处复用：
//  1. `ShareCardSheet` 的 sheet 内预览（用户切主题时实时看变化）
//  2. `ShareCardExporter.render(...)` 用 `ImageRenderer` 渲染成 PNG 导出
//
//  把"卡片本体"和"sheet 容器"拆开是为了：
//  - 导出图片时不能把 sheet 的关闭按钮 / 主题选择器一起截进去
//  - 单测 / Preview 可以单独渲染卡片本体不依赖 sheet 上下文
//
//  布局规范（来自 issue HOM-173 dong4j 最终方案 + Magazine v2 image 参考）：
//  ┌─────────────────────────────────────┐
//  │ ✦ STARCAT       OPEN SOURCE · ID    │  ← 顶栏（两端对齐）
//  ├─────────────────────────────────────┤
//  │           [圆形大头像 96pt]          │  ← 头像区
//  │            dong4j                    │
//  │            @dong4j                   │
//  │           "一句签名…"                  │
//  ├─────────────────────────────────────┤
//  │   ⭐ 1.2K   👥 236   📦 4.8K          │  ← 三栏统计
//  │   Starred  Followers Following       │
//  ├─────────────────────────────────────┤
//  │  CONTRIBUTION GRAPH                  │  ← 草坪
//  │  ░▓▓░▓▓▓▓░░▓▓▓▓▓▓░▓▓▓▓               │
//  │  365 days · 1,234 contributions      │
//  ├─────────────────────────────────────┤
//  │  > Generated by Starcat · starcat.app│  ← 底部品牌注脚
//  └─────────────────────────────────────┘
//
//  尺寸：固定 400pt × 560pt（不是 520——加入 contribution 详情行后实测 520
//  会让贡献图与品牌注脚挤在一起）。导出时按 @3x → 1200×1680 PNG。
//
//  设计权衡：
//  - **不再做"按头像取主色"渐变背景**：用户最终方案明确要求三套主题保持一致，
//    每种主题颜色都是固定的（极简黑 / 热力橙 / GitHub 绿），让"主题"成为表达主体，
//    而不是头像主色。这也避免了导出图依赖 KFImage 异步取色的复杂性。
//  - **草坪只用静态版本**：贪吃蛇动画在导出图里没意义，渲染成静态草坪即可。
//    复用 `ContributionGraphView` 的格子尺寸 / 圆角风格保证 sidebar 与卡片观感一致。
//

import SwiftUI
import Kingfisher

/// 分享卡片本体（纯视觉，无任何交互）。
///
/// 用法：
/// ```swift
/// ShareCardContent(
///     user: user,
///     starredCount: viewModel.totalCount,
///     contribution: contributionService.payload,
///     theme: .githubGreen,
///     isProUser: settings.isProUser
/// )
/// .frame(width: 400, height: 560)
/// ```
struct ShareCardContent: View {

    /// 当前登录用户。
    let user: GitHubUserDTO

    /// 本地缓存的 starred 数量（来自 `HomeViewModel.totalCount`，与 sidebar 同源）。
    /// 远程 followers/following 走 `user.followers/following`（GitHub `/user` 接口返回）。
    let starredCount: Int

    /// 贡献草坪 payload。nil 时显示 7×53 占位灰格（不阻塞分享）。
    let contribution: ContributionCalendarPayload?

    /// 当前主题。
    let theme: ShareCardTheme

    /// 当前用户是否为 Pro 用户。Pro 用户头像显示 Pro 标识。
    var isProUser: Bool = false

    /// 卡片宽度。固定 400pt，导出时通过 `ImageRenderer.scale` 放大到 @3x。
    static let canvasWidth: CGFloat = 400
    /// 卡片高度。560pt = 顶栏 36 + 头像区 200 + 统计区 64 + 草坪区 144 + 注脚 36 + 内边距。
    static let canvasHeight: CGFloat = 560

    // MARK: - 派生

    /// 当前主题色板（每个 body 计算一次，避免 View tree 内多处重复访问）。
    private var palette: ShareCardPalette { theme.palette }

    /// 卡片背景：双色线性渐变（顶部稍亮 → 底部主色），让深色卡片有微弱呼吸感。
    /// 不做 RadialGradient 是因为分享卡尺寸 400×560 矩形比例下椭圆光斑会偏中心，
    /// 顶 → 底线性更稳定，且与 `cardBackgroundSecondary` 的视觉用途（"顶部高光"）匹配。
    private var backgroundGradient: LinearGradient {
        LinearGradient(
            colors: [palette.cardBackgroundSecondary, palette.cardBackground],
            startPoint: .top,
            endPoint: .bottom
        )
    }

    var body: some View {
        // **HOM-173 follow-up（2026-06-06）**：按 theme.layout 走两条独立渲染路径——
        // - magazine：既有 3 个主题（minimal / heatOrange / githubGreen），保持原版本
        // - idCard：新增白卡 / 黑卡，去掉草坪 + follow stats，右下角换 QR 码
        // 两条路径完全分离，对既有主题零影响。
        Group {
            switch theme.layout {
            case .magazine:
                magazineBody
            case .idCard:
                idCardBody
            }
        }
        .frame(width: Self.canvasWidth, height: Self.canvasHeight)
        .background(backgroundGradient)
        .overlay(
            // 极细 1pt 描边让卡片边界与外层 sheet 背景区分
            RoundedRectangle(cornerRadius: 24)
                .stroke(palette.cardBorder, lineWidth: 1)
        )
        .clipShape(RoundedRectangle(cornerRadius: 24))
    }

    // MARK: - Magazine 布局（HOM-173 v1，既有主题）

    /// 杂志卡布局：顶栏 + 头像 + 链接行（含QR） + 三栏统计 + 草坪 + 注脚。
    /// HOM-174 follow-up：链接区域右侧添加 QR 码。
    @ViewBuilder
    private var magazineBody: some View {
        VStack(spacing: 0) {
            topBar
            avatarSection
                .padding(.top, 18)
                .padding(.bottom, 14)
            // HOM-174：链接行 + QR 码
            magazineLinksSection
                .padding(.bottom, 14)
            divider
            statsSection
                .padding(.vertical, 18)
            divider
            contributionSection
                .padding(.vertical, 18)
            divider
            footerBar
        }
        .padding(.horizontal, 24)
        .padding(.vertical, 20)
    }

    /// Magazine 布局的链接行：左侧链接列表 + 右侧 QR 码。
    @ViewBuilder
    private var magazineLinksSection: some View {
        HStack(alignment: .top, spacing: 12) {
            // 左侧链接列表
            profileLinksSection

            // 右侧 QR 码
            qrCodeView
        }
    }

    // MARK: - 顶栏

    /// 顶栏：左侧"✦ STARCAT" 品牌名，右侧"OPEN SOURCE · DEVELOPER ID" 副标题。
    /// 字号刻意拉小（11pt）+ 大字间距（tracking），呼应"杂志封面"质感而非 UI 标题。
    @ViewBuilder
    private var topBar: some View {
        HStack(alignment: .center, spacing: 8) {
            Text("✦ STARCAT")
                .font(.system(size: 12, weight: .black, design: .rounded))
                .foregroundStyle(palette.primaryText)
                .tracking(2)

            Spacer()

            Text("OPEN SOURCE · DEVELOPER ID")
                .font(.system(size: 9, weight: .semibold, design: .monospaced))
                .foregroundStyle(palette.tertiaryText)
                .tracking(1.5)
        }
    }

    // MARK: - 头像 + 身份区

    /// 头像（96pt 圆形）+ 显示名 + @login + Bio + Pro 标识。
    /// Bio 最多 2 行；nil/空串时省略不留空白。
    /// Pro 用户在头像右下角显示 Pro 徽章。
    @ViewBuilder
    private var avatarSection: some View {
        VStack(spacing: 10) {
            ZStack(alignment: .bottomTrailing) {
                // 96pt 头像 + 描边（用 accent 色 2pt 描边强化主题感）
                RemoteAvatar(urlString: user.avatarUrl, size: 96, showBorder: false)
                    .overlay(
                        Circle().stroke(palette.accent, lineWidth: 2)
                    )

                // Pro 用户标识：彩虹渐变徽章
                if isProUser {
                    Text("PRO")
                        .font(.system(size: 8, weight: .black))
                        .foregroundStyle(.white)
                        .padding(.horizontal, 5)
                        .padding(.vertical, 2)
                        .background {
                            Capsule()
                                .fill(
                                    LinearGradient(
                                        colors: [.yellow, .orange, .pink],
                                        startPoint: .topLeading,
                                        endPoint: .bottomTrailing
                                    )
                                )
                                .shadow(color: .black.opacity(0.18), radius: 2, y: 1)
                        }
                        .overlay {
                            Capsule()
                                .stroke(.white.opacity(0.75), lineWidth: 0.7)
                        }
                        .offset(x: 8, y: 0)
                }
            }

            VStack(spacing: 2) {
                // 显示名（name 优先，缺失 fallback login）
                Text(user.name?.isEmpty == false ? user.name! : user.login)
                    .font(.system(size: 22, weight: .bold, design: .rounded))
                    .foregroundStyle(palette.primaryText)
                    .lineLimit(1)
                    .minimumScaleFactor(0.7)

                // HOM-174：仅在 name 与 login 不同时显示 @login，避免重复（如 "dong4j" + "@dong4j"）
                if user.name?.lowercased() != user.login.lowercased() {
                    Text("@\(user.login)")
                        .font(.system(size: 12, weight: .medium, design: .monospaced))
                        .foregroundStyle(palette.secondaryText)
                        .lineLimit(1)
                }
            }

            // Bio：非空才渲染。Bio 中 GitHub 不渲染 @mention/markdown，原样平文本展示。
            if let bio = user.bio, !bio.isEmpty {
                Text("“\(bio)”")
                    .font(.system(size: 12, weight: .regular))
                    .italic()
                    .foregroundStyle(palette.secondaryText)
                    .multilineTextAlignment(.center)
                    .lineLimit(2)
                    .padding(.top, 2)
                    .padding(.horizontal, 8)
            }
        }
        .frame(maxWidth: .infinity)
    }

    // MARK: - 三栏统计

    /// 三栏：Starred / Followers / Following。
    /// Starred 走本地 `starredCount`（与 sidebar 同源），followers/following 走 `/user` 字段。
    @ViewBuilder
    private var statsSection: some View {
        HStack(spacing: 0) {
            statCell(value: starredCount, labelKey: "sharecard.stats.starred", symbol: "star.fill")
            statDivider
            statCell(value: user.followers ?? 0, labelKey: "sharecard.stats.followers", symbol: "person.2.fill")
            statDivider
            statCell(value: user.following ?? 0, labelKey: "sharecard.stats.following", symbol: "person.fill")
        }
    }

    /// 三栏分隔条：高度 32pt 的细分隔线，颜色用主题 divider 色。
    private var statDivider: some View {
        Rectangle()
            .fill(palette.divider)
            .frame(width: 1, height: 32)
    }

    /// 单栏统计：图标 + 数字（大字）+ label（小字 secondary）。
    /// 数字用 SF Rounded + monospacedDigit 保证三栏对齐。
    @ViewBuilder
    private func statCell(value: Int, labelKey: LocalizedStringKey, symbol: String) -> some View {
        VStack(spacing: 4) {
            HStack(spacing: 4) {
                Image(systemName: symbol)
                    .font(.system(size: 11, weight: .semibold))
                    .foregroundStyle(palette.accent)
                Text(formatCompact(value))
                    .font(.system(size: 20, weight: .bold, design: .rounded))
                    .monospacedDigit()
                    .foregroundStyle(palette.primaryText)
            }
            Text(labelKey)
                .font(.system(size: 9, weight: .medium))
                .foregroundStyle(palette.tertiaryText)
                .tracking(1)
                .textCase(.uppercase)
        }
        .frame(maxWidth: .infinity)
    }

    /// 把整数格式化成紧凑形式（1234 → 1.2K，4823 → 4.8K，999 → 999）。
    /// 卡片宽度受限，5 位以上数字会挤占其他栏，4 位以上自动 K-suffix。
    private func formatCompact(_ n: Int) -> String {
        if n < 1000 { return String(n) }
        let k = Double(n) / 1000.0
        return String(format: "%.1fK", k)
    }

    // MARK: - 草坪

    /// 贡献草坪：53 周 × 7 天，颜色按 `theme.palette.contribution` 渲染。
    ///
    /// 不复用 `ContributionGraphView` 是因为：
    /// - 那个 view 强依赖 `@Environment(\.colorScheme)` 自动切 light/dark 调色板，
    ///   导出图需要固定主题色而不是跟随系统。
    /// - 那个 view 还挂了贪吃蛇 animator + TimelineView，导出图都不需要。
    /// - 重新写一份纯静态版本（约 30 行 Canvas）反而更轻、更可控。
    @ViewBuilder
    private var contributionSection: some View {
        VStack(alignment: .leading, spacing: 6) {
            HStack {
                Text("sharecard.contribution.title")
                    .font(.system(size: 9, weight: .semibold, design: .monospaced))
                    .tracking(1.5)
                    .foregroundStyle(palette.tertiaryText)
                Spacer()
                if let total = contribution?.totalContributions {
                    Text(String(format: String(localized: "sharecard.contribution.totalCount"), total))
                        .font(.system(size: 9, weight: .semibold, design: .monospaced))
                        .foregroundStyle(palette.secondaryText)
                }
            }

            ContributionStaticGrid(
                payload: contribution,
                palette: palette.contribution
            )
            .aspectRatio(53.0 / 7.0 * (10.0 / 12.0), contentMode: .fit)
            // 53 列 × 7 行 = aspect 7.57:1（10pt 宽 × 12pt 高）；
            // 卡片可用宽度 ~352pt（400 - 24×2 padding），渲染高度 ~46pt 视觉合适
        }
    }

    // MARK: - 链接行（HOM-174 新增）

    /// 个人主页链接行：GitHub 主页、blog、email 等。
    /// HOM-174 follow-up：
    /// - 链接改成每行一个（VStack 布局）
    /// - 图标带绿色背景
    /// - 最多显示 3 个链接
    @ViewBuilder
    private var profileLinksSection: some View {
        let links = Array(makeProfileLinks().prefix(3))
        if !links.isEmpty {
            VStack(alignment: .leading, spacing: 6) {
                ForEach(links) { link in
                    profileLinkItem(link: link)
                }
            }
            .frame(maxWidth: .infinity, alignment: .leading)
        }
    }

    /// 单个链接项：绿色背景图标 + 文字。
    @ViewBuilder
    private func profileLinkItem(link: ShareCardLinkItem) -> some View {
        HStack(spacing: 6) {
            // 绿色背景图标
            ZStack {
                RoundedRectangle(cornerRadius: 4)
                    .fill(Color.green.opacity(0.2))
                    .frame(width: 20, height: 20)
                Image(systemName: link.symbolName)
                    .font(.system(size: 10, weight: .medium))
                    .foregroundStyle(.green)
            }
            Text(link.displayText)
                .font(.system(size: 10, weight: .medium))
                .foregroundStyle(palette.secondaryText)
                .lineLimit(1)
        }
    }

    /// 构建链接列表（用于分享卡导出图的静态展示）。
    private func makeProfileLinks() -> [ShareCardLinkItem] {
        var items: [ShareCardLinkItem] = []

        // GitHub 主页（始终显示）
        items.append(ShareCardLinkItem(
            symbolName: "link",
            displayText: user.htmlUrl ?? "github.com/\(user.login)"
        ))

        // blog / homepage
        if let blog = user.blog?.trimmingCharacters(in: .whitespacesAndNewlines), !blog.isEmpty {
            let displayText = blog.hasPrefix("http") ? blog : "https://\(blog)"
            items.append(ShareCardLinkItem(
                symbolName: "globe",
                displayText: displayText
            ))
        }

        // email
        if let email = user.email?.trimmingCharacters(in: .whitespacesAndNewlines), !email.isEmpty {
            items.append(ShareCardLinkItem(
                symbolName: "envelope",
                displayText: email
            ))
        }

        return items
    }

    // MARK: - 通用元素

    /// 全宽细分隔线（顶/中/底分区用）。
    private var divider: some View {
        Rectangle()
            .fill(palette.divider)
            .frame(height: 0.7)
    }

    /// 底部品牌注脚：> Generated by Starcat · starcat.app
    /// 用等宽字 + 终端命令提示符风格，向 Gemini / Claude 方案致敬。
    @ViewBuilder
    private var footerBar: some View {
        HStack {
            Text("> Generated by Starcat")
                .font(.system(size: 9, weight: .medium, design: .monospaced))
                .foregroundStyle(palette.tertiaryText)
                .tracking(0.5)
            Spacer()
            Text("starcat.app")
                .font(.system(size: 9, weight: .medium, design: .monospaced))
                .foregroundStyle(palette.accent)
        }
    }

    // MARK: - ID Card 布局（HOM-173 v2，2026-06-06 新增）

    /// ID 卡布局：大圆角头像主图 + 用户名 + Bio + 链接行 + 底部（stats + QR + footer）。
    /// HOM-174 follow-up：
    /// - 添加链接行（每行一个，带绿色背景图标）
    /// - 底部添加 Generated by Starcat
    /// - 优化垂直间距减少空白
    ///
    /// 布局结构：
    /// - 顶部：大圆角矩形头像（卡片宽度减边距），底部加渐变带过渡到下方文字
    /// - 中部：用户名 + verified 勾 + Bio（最多 2 行，nil/空 时省略）
    /// - 链接行（GitHub / homepage / email，每行一个）
    /// - 底部：3 个 pill stat（⭐ Starred + 👥 Followers + 👥 Following）+ QR 码
    /// - 底部注脚：Generated by Starcat
    @ViewBuilder
    private var idCardBody: some View {
        VStack(spacing: 0) {
            idCardAvatar
                .padding(.top, 16)

            VStack(alignment: .leading, spacing: 4) {
                idCardIdentity
                idCardBio
            }
            .frame(maxWidth: .infinity, alignment: .leading)
            .padding(.horizontal, 24)
            .padding(.top, 14)

            // 链接行
            profileLinksSection
                .padding(.horizontal, 24)
                .padding(.top, 10)

            Spacer(minLength: 8)

            idCardBottomRow
                .padding(.horizontal, 24)

            // HOM-174：底部注脚
            idCardFooter
                .padding(.horizontal, 24)
                .padding(.top, 8)
                .padding(.bottom, 16)
        }
    }

    /// ID 卡顶部头像区。
    /// 圆角矩形头像（不是圆形）+ 底部渐变虚化，模拟设计图里头像填充上半部分的视觉。
    @ViewBuilder
    private var idCardAvatar: some View {
        // 卡片宽 400 - 左右 padding 20 = 360pt 头像方块；高度按 0.78 比例避免太占垂直空间
        let avatarSide: CGFloat = Self.canvasWidth - 40
        let avatarHeight: CGFloat = avatarSide * 0.78
        ZStack(alignment: .bottom) {
            avatarFillView
                .frame(width: avatarSide, height: avatarHeight)
                .clipShape(RoundedRectangle(cornerRadius: 18))
                .overlay(
                    RoundedRectangle(cornerRadius: 18)
                        .stroke(palette.cardBorder, lineWidth: 0.5)
                )

            // 头像底部 → 卡片底色的淡入渐变带，让头像和下方文字区无硬边过渡
            LinearGradient(
                colors: [palette.cardBackground.opacity(0.0),
                         palette.cardBackground.opacity(0.55)],
                startPoint: .top, endPoint: .bottom
            )
            .frame(width: avatarSide, height: 60)
            .clipShape(
                UnevenRoundedRectangle(
                    bottomLeadingRadius: 18,
                    bottomTrailingRadius: 18
                )
            )
        }
        .frame(maxWidth: .infinity)
    }

    /// 头像填充视图。设计图里头像几乎覆盖卡片上半部分，需要"方形填充"——
    /// 不能用 `RemoteAvatar`（强制 Circle clip 会丢四角），改直接用 KFImage scaledToFill。
    @ViewBuilder
    private var avatarFillView: some View {
        if let urlString = user.avatarUrl,
           !urlString.isEmpty,
           let url = URL(string: urlString) {
            // KFImage：与 sidebar / Magazine 卡同一份 Kingfisher 缓存，命中率近 100%
            KFImage(url)
                .resizable()
                .placeholder {
                    Rectangle()
                        .fill(palette.cardBackgroundSecondary)
                        .overlay(
                            Image(systemName: "person.fill")
                                .font(.system(size: 60))
                                .foregroundStyle(palette.tertiaryText)
                        )
                }
                .fade(duration: 0.15)
                .scaledToFill()
        } else {
            // 无 avatarUrl：渐变占位 + person 图标
            ZStack {
                LinearGradient(
                    colors: [palette.cardBackgroundSecondary, palette.cardBackground],
                    startPoint: .topLeading, endPoint: .bottomTrailing
                )
                Image(systemName: "person.fill")
                    .font(.system(size: 80, weight: .light))
                    .foregroundStyle(palette.tertiaryText)
            }
        }
    }

    /// ID 卡身份行：用户名 + verified 勾。
    @ViewBuilder
    private var idCardIdentity: some View {
        HStack(alignment: .center, spacing: 8) {
            Text(user.name?.isEmpty == false ? user.name! : user.login)
                .font(.system(size: 26, weight: .bold, design: .rounded))
                .foregroundStyle(palette.primaryText)
                .lineLimit(1)
                .minimumScaleFactor(0.6)

            // verified 勾——白卡用黑勾、黑卡用白勾，与设计图视觉等价
            Image(systemName: "checkmark.seal.fill")
                .font(.system(size: 18))
                .foregroundStyle(palette.accent)
        }
    }

    /// ID 卡 Bio 行。空 / nil 时不渲染。
    @ViewBuilder
    private var idCardBio: some View {
        if let bio = user.bio, !bio.isEmpty {
            Text(bio)
                .font(.system(size: 13, weight: .regular))
                .foregroundStyle(palette.secondaryText)
                .lineLimit(2)
                .multilineTextAlignment(.leading)
                .fixedSize(horizontal: false, vertical: true)
        }
    }

    /// ID 卡底部行：左侧 3 个 pill stats，右侧 QR 码。
    ///
    /// HOM-174 follow-up：改为 3 个 stat（Starred + Followers + Following），
    /// 与 magazine 布局的前 3 个主题保持一致。
    @ViewBuilder
    private var idCardBottomRow: some View {
        HStack(alignment: .center) {
            VStack(alignment: .leading, spacing: 8) {
                idCardStatPill(symbol: "star.fill",
                               value: starredCount,
                               labelKey: "sharecard.stats.starred")
                idCardStatPill(symbol: "person.2.fill",
                               value: user.followers ?? 0,
                               labelKey: "sharecard.stats.followers")
                idCardStatPill(symbol: "person.fill",
                               value: user.following ?? 0,
                               labelKey: "sharecard.stats.following")
            }

            Spacer()

            qrCodeView
        }
    }

    /// 单个 stat pill：圆形 accent 底图标 + 数字 + 小标签。
    @ViewBuilder
    private func idCardStatPill(symbol: String, value: Int, labelKey: LocalizedStringKey) -> some View {
        HStack(spacing: 8) {
            ZStack {
                Circle()
                    .fill(palette.accent)
                    .frame(width: 22, height: 22)
                Image(systemName: symbol)
                    .font(.system(size: 11, weight: .bold))
                    .foregroundStyle(palette.onAccent)
            }
            Text(formatCompact(value))
                .font(.system(size: 14, weight: .semibold, design: .rounded))
                .foregroundStyle(palette.primaryText)
                .monospacedDigit()
            Text(labelKey)
                .font(.system(size: 10, weight: .medium))
                .foregroundStyle(palette.tertiaryText)
                .textCase(.uppercase)
                .tracking(0.5)
        }
    }

    /// QR 码视图。内容：用户 GitHub 主页 URL（`https://github.com/{login}`）。
    ///
    /// 视觉：64pt QR + 6pt 容器内边距 = 76pt 容器；容器底色 = onAccent（与 stats pill 反色一致）。
    /// 白卡：黑容器 + 白 QR；黑卡：白容器 + 黑 QR——两种模式都保证扫码对比度。
    ///
    /// HOM-174 follow-up：QR 码不使用 template rendering，直接显示原生黑白图像
    /// （QR 需要高对比度，template tinting 会导致扫码失败）。
    @ViewBuilder
    private var qrCodeView: some View {
        let url = "https://github.com/\(user.login)"
        let qrImage = QRCodeGenerator.generate(text: url, sizePoints: 64)

        ZStack {
            RoundedRectangle(cornerRadius: 14)
                .fill(palette.onAccent)
                .frame(width: 76, height: 76)

            if let qrImage {
                // QR码直接显示，不使用template模式以保持高对比度
                Image(nsImage: qrImage)
                    .interpolation(.none)
                    .resizable()
                    .frame(width: 64, height: 64)
            } else {
                // 极端兜底：QR 生成失败时显示 SF Symbol qrcode 图标
                Image(systemName: "qrcode")
                    .font(.system(size: 36, weight: .regular))
                    .foregroundStyle(palette.accent)
            }
        }
        .accessibilityLabel(Text(verbatim: url))
    }

    /// ID 卡底部注脚：Generated by Starcat · starcat.app
    @ViewBuilder
    private var idCardFooter: some View {
        HStack {
            Text("> Generated by Starcat")
                .font(.system(size: 9, weight: .medium, design: .monospaced))
                .foregroundStyle(palette.tertiaryText)
                .tracking(0.5)
            Spacer()
            Text("starcat.app")
                .font(.system(size: 9, weight: .medium, design: .monospaced))
                .foregroundStyle(.green)
        }
    }
